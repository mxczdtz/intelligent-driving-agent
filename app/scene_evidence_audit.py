r"""
Phase 3.5 — evidence-reference audit for a saved Phase 3.4 Qwen risk report.

Reads an EXISTING llm_frame_*.json generated by app.scene_llm_risk.
It never loads a model, downloads weights, changes the existing report, or
uses simulator ground truth. This is an attribution / consistency audit,
not a new risk predictor or semantic truth verifier.

Example (PowerShell, project root):
    & $PY -m app.scene_evidence_audit `
      --risk-report ".\evidence\scene_llm_risk\llm_frame_00003488_20261116_164941_919224.json"

Output: a new evidence/scene_evidence_audit/audit_frame_*.json
"""
from __future__ import annotations

import argparse
from datetime import datetime
import json
from pathlib import Path
import re
import sys
from typing import Any

SCHEMA_VERSION = "scene_evidence_audit.v1"
KNOWN_PREFIXES = {"yolo", "vlm", "ego"}

# Only explicit SOURCE mentions can be checked deterministically.
# General facts such as "missing TTC" do not require a positive reference:
# their support comes from the payload's stated measurement limitations.
SOURCE_WORDS: dict[str, re.Pattern[str]] = {
    "yolo": re.compile(r"(?<![a-z])yolo(?![a-z])", re.I),
    "vlm": re.compile(r"(?<![a-z])vlm(?![a-z])", re.I),
    "ego": re.compile(r"自车速度|ego(?:[_ -]?speed)?", re.I),
}
CONFLICT_WORDS = re.compile(r"不一致|矛盾|冲突|相互否定|contradict|disagree", re.I)
UNCERTAIN_WORDS = re.compile(
    r"未经验证|未证实|未验证|未对齐|待核实|可能|无法确认|不能确认|"
    r"未必|并非|无法证明|尚不能确认|unverified|uncertain|not confirmed",
    re.I,
)
CONFIRMED_CONFLICT_STATUSES = {
    # A count disagreement is a difference between model outputs,
    # *not* independent verification that either model is right.
    "count_disagreement_needs_image_review",
}


def load_json(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8-sig") as handle:
        data = json.load(handle)
    if not isinstance(data, dict):
        raise ValueError("Expected a top-level JSON object.")
    return data


def str_list(value: Any, field: str) -> list[str]:
    if not isinstance(value, list) or not all(isinstance(v, str) for v in value):
        raise ValueError(f"{field} must be an array of strings.")
    return value


def extract_sources(text: str) -> set[str]:
    # Do not infer evidence source from arbitrary semantic words.
    return {name for name, pattern in SOURCE_WORDS.items() if pattern.search(text)}


def get_report_fields(report: dict[str, Any]) -> tuple[dict[str, Any], dict[str, Any]]:
    if report.get("schema_version") != "scene_llm_risk.v1":
        raise ValueError("Expected scene_llm_risk.v1 report.")
    payload = report.get("input_to_llm")
    decision = report.get("final_research_decision")
    if not isinstance(payload, dict) or not isinstance(decision, dict):
        raise ValueError("Missing input_to_llm / final_research_decision.")
    return payload, decision


def audit_report(report: dict[str, Any]) -> dict[str, Any]:
    """Inspect evidence-reference quality, not the visual or physical truth."""
    payload, decision = get_report_fields(report)
    factors = str_list(decision.get("key_factors"), "key_factors")
    uncertainties = str_list(decision.get("uncertainty"), "uncertainty")
    references = str_list(decision.get("evidence_refs"), "evidence_refs")
    if not factors:
        raise ValueError("Decision has no key_factors; audit requires an existing decision.")
    decision_level = decision.get("risk_level")
    if decision_level not in {"unknown", "low", "medium", "high"}:
        raise ValueError("Unexpected final risk_level.")
    if report.get("validation_status") not in {"valid", "valid_after_retry", "fallback"}:
        raise ValueError("Unknown validation status.")

    available = payload.get("available_evidence_refs")
    if not isinstance(available, list) or not all(isinstance(v, str) for v in available):
        raise ValueError("Missing available_evidence_refs from model input.")
    duplicate_refs = sorted({r for r in references if references.count(r) > 1})
    unknown_refs = sorted(set(references) - set(available))
    bad_prefixes = sorted({
        r for r in references if r.partition(":")[0] not in KNOWN_PREFIXES
    })

    provided_types = {
        ref.partition(":")[0]
        for ref in references
        if ":" in ref and ref.partition(":")[0] in KNOWN_PREFIXES
    }
    checks = payload.get("cross_checks")
    if not isinstance(checks, list):
        checks = []
    check_statuses = sorted({
        str(c.get("status", ""))
        for c in checks if isinstance(c, dict) and c.get("status")
    })
    any_count_difference = bool(
        CONFIRMED_CONFLICT_STATUSES.intersection(check_statuses)
    )
    notes = []
    issues = []
    details = []

    for idx, factor in enumerate(factors):
        claimed_sources = extract_sources(factor)
        missing_sources = sorted(claimed_sources - provided_types)
        flag_codes: list[str] = []
        if missing_sources:
            flag_codes.append("explicit_source_reference_missing")
            issues.append(
                f"Factor {idx + 1} names {', '.join(missing_sources).upper()} "
                "but the global evidence_refs list has no matching source reference."
            )
        if (
            claimed_sources == {"yolo", "vlm"}
            and CONFLICT_WORDS.search(factor)
            and not UNCERTAIN_WORDS.search(factor)
            and not any_count_difference
        ):
            flag_codes.append("unqualified_cross_model_conflict")
            issues.append(
                f"Factor {idx + 1} states a YOLO/VLM conflict as fact, "
                "but saved checks only support agreement/uncertainty or "
                "missing cross-validation. Inspect the actual image."
            )
        details.append({
            "factor_number": idx + 1,
            "original_text": factor,
            "explicitly_named_sources": sorted(claimed_sources),
            "matching_source_types_in_global_refs": sorted(
                claimed_sources & provided_types
            ),
            "missing_source_types_in_global_refs": missing_sources,
            "flag_codes": flag_codes,
            "status": "needs_review" if flag_codes else "not_flagged_not_verified",
        })

    if duplicate_refs:
        issues.append("Repeated evidence IDs in final decision: " + ", ".join(duplicate_refs))
    if unknown_refs:
        issues.append("Unknown evidence IDs: " + ", ".join(unknown_refs))
    if bad_prefixes:
        issues.append("Unsupported evidence prefixes: " + ", ".join(bad_prefixes))

    if not issues:
        notes.append(
            "No obvious missing source types were detected by narrow rules; "
            "this does NOT establish per-factor grounding or factual correctness."
        )
    notes.extend([
        "The decision only has a GLOBAL evidence_refs list, not per-factor references.",
        "Source-name matching is a conservative heuristic; wording that omits model "
        "names may still be ungrounded and cannot be validated by this script.",
        "An absent YOLO traffic-light detection does NOT prove the VLM traffic-light "
        "description false; treat signal-color claims as unverified.",
        "This is a post-hoc audit. No CARLA truth is used and no risk levels are changed.",
    ])

    return {
        "schema_version": SCHEMA_VERSION,
        "world_frame": payload.get("world_frame"),
        "llm_validation_status": report.get("validation_status"),
        "final_research_risk_unchanged": decision_level,
        "available_source_types": sorted({
            x.partition(":")[0] for x in available
            if isinstance(x, str) and ":" in x
        }),
        "cited_evidence_refs": references,
        "cited_source_types": sorted(provided_types),
        "cross_check_statuses": check_statuses,
        "factor_audit": details,
        "uncertainty_text_unverified": uncertainties,
        "issues": issues,
        "audit_status": "needs_review" if issues else "no_obvious_source_mismatch",
        "audit_notes": notes,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--risk-report", required=True, type=Path)
    parser.add_argument("--output", type=Path, default=None)
    args = parser.parse_args()
    risk_path = args.risk_report.expanduser().resolve()
    if not risk_path.is_file():
        raise FileNotFoundError(f"Risk report not found: {risk_path}")
    report = load_json(risk_path)
    audit = audit_report(report)

    root = Path(__file__).resolve().parent.parent
    output_dir = root / "evidence" / "scene_evidence_audit"
    destination = args.output or (
        output_dir /
        f"audit_frame_{int(audit['world_frame']):08d}_{datetime.now():%Y%m%d_%H%M%S_%f}.json"
    )
    destination = destination.resolve()
    if destination == risk_path or destination.exists():
        raise FileExistsError("Refusing to overwrite an existing report.")
    destination.parent.mkdir(parents=True, exist_ok=True)
    result = {
        "created_at": datetime.now().astimezone().isoformat(timespec="seconds"),
        "source_risk_report": str(risk_path),
        **audit,
    }
    destination.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")

    print("=== Phase 3.5: evidence-reference quality audit ===")
    print("Frame:", audit["world_frame"])
    print("Qwen JSON validation:", audit["llm_validation_status"])
    print("Original final research risk:", audit["final_research_risk_unchanged"])
    print("Cited evidence:", json.dumps(audit["cited_evidence_refs"], ensure_ascii=False))
    print("Audit status:", audit["audit_status"])
    for factor in audit["factor_audit"]:
        print(f"Factor {factor['factor_number']}:", factor["original_text"])
        print("  Source flags:",
              ", ".join(factor["flag_codes"]) if factor["flag_codes"] else "(none detected)")
    for issue in audit["issues"]:
        print("Review:", issue)
    print("Report:", destination)
    print("PASS: offline evidence audit saved; no model re-run and no risk change")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, TypeError, ValueError, KeyError, json.JSONDecodeError) as exc:
        print(f"ERROR: {type(exc).__name__}: {exc}", file=sys.stderr)
        raise SystemExit(1)
